const router = require("express").Router();
const protect = require("../middleware/authMiddleware");
const authorize = require("../middleware/roleMiddleware");
const requests = require("../controllers/adminRequestController");
const users = require("../controllers/adminUserController");
const services = require("../controllers/serviceController");
router.use(protect, authorize("admin"));
router.get("/dashboard", require("../controllers/adminDashboardController"));
router.get("/requests", requests.listRequests);
router.get("/requests/:id", requests.getRequest);
router.patch("/requests/:id/status", requests.updateRequest);
router.patch("/requests/:id", requests.updateRequest);
router.get("/users", users.listUsers);
router.get("/staff", users.staffOptions);
router.post("/users", users.createUser);
router.get("/users/:id", users.getUser);
router.patch("/users/:id/role", users.changeRole);
router.patch("/users/:id", users.updateUser);
router.delete("/users/:id", users.deactivateUser);
router.get("/services", services.listServices);
router.get("/services/:id", services.getService);
router.post("/services", services.createService);
router.patch("/services/:id", services.updateService);
router.delete("/services/:id", services.deleteService);
module.exports = router;
