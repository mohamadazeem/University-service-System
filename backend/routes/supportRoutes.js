const router = require("express").Router();
const protect = require("../middleware/authMiddleware");
const authorize = require("../middleware/roleMiddleware");
const c = require("../controllers/supportController");
router.use(protect);
router.get("/appointments/availability", authorize("student", "admin"), c.slots);
router.get("/appointments", authorize("student"), c.list(c.Appointment));
router.post("/appointments", authorize("student"), c.book);
router.patch("/appointments/:id", authorize("student"), require("../controllers/appointmentController").review);
router.get("/complaints/:id", authorize("student"), require("../controllers/complaintController").details);
router.get("/complaints", authorize("student"), c.list(c.Complaint));
router.post("/complaints", authorize("student"), c.submitComplaint);
router.get("/notifications", c.notifications);
router.get("/notifications/unread-count", require("../controllers/notificationController").count);
router.get("/notifications/:id/related", authorize("student"), require("../controllers/notificationController").related);
router.patch("/notifications/read-all", require("../controllers/notificationController").readAll);
router.patch("/notifications/:id/read", c.readNotification);
module.exports = router;
